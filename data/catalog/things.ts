import { hasLicensedPhoto, licensedPhotoFor } from "@/data/catalog/licensedPhotos";
import { commonsImage, type CatalogItem } from "@/data/catalog/types";

function sport(name: string, file: string | null, wikipedia?: string): CatalogItem {
  return {
    name,
    categories: ["sports"],
    image: file ? commonsImage(file) : null,
    metadata: { wikipedia: wikipedia ?? name },
  };
}

function car(name: string, file: string | null, wikipedia?: string): CatalogItem {
  return {
    name,
    categories: ["cars"],
    image: file ? commonsImage(file) : null,
    metadata: wikipedia ? { wikipedia } : {},
  };
}

function food(name: string, file: string | null, wikipedia?: string): CatalogItem {
  return {
    name,
    categories: ["food"],
    image: file ? commonsImage(file) : null,
    metadata: wikipedia ? { wikipedia } : {},
  };
}

function brand(name: string): CatalogItem {
  return {
    name,
    categories: ["brands"],
    image: licensedPhotoFor(name),
  };
}

